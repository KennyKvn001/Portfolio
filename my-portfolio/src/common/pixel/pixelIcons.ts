export type PixelIconName = keyof typeof SPRITES;

const iconCache = new Map<PixelIconName, PixelGrid>();

export function isPixelIconName(name: string): name is PixelIconName {
    return name in SPRITES;
}

export function getIconGrid(name: PixelIconName): PixelGrid {
    const cached = iconCache.get(name);
    if (cached) {
        return cached;
    }
    const grid = parseSprite(SPRITES[name]);
    iconCache.set(name, grid);
    return grid;
}
