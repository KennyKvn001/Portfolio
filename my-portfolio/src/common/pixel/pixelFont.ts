const glyphCache = new Map<string, PixelGrid>();

function getGlyph(character: string): PixelGrid {
    const key = character in GLYPHS ? character : FALLBACK_CHARACTER;
    const cached = glyphCache.get(key);
    if (cached) {
        return cached;
    }
    const glyph = parseSprite(GLYPHS[key]);
    glyphCache.set(key, glyph);
    return glyph;
}

/** Renders text in the pixel font. Lower case is drawn as upper case. */
export function textToGrid(text: string): PixelGrid {
    return joinHorizontally(Array.from(text.toUpperCase(), getGlyph), LETTER_SPACING);
}
